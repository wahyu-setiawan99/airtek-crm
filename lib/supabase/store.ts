import "server-only";
import type { SupabaseClient } from "@supabase/supabase-js";
import { STORE_VERSION } from "@/lib/demo/seed";
import { createAdminClient } from "@/lib/supabase/admin";
import type { Store } from "@/types/crm";

type TableName = Exclude<keyof Store, "version" | "seeded_on">;
type Row = Record<string, unknown>;

type TableSpec = {
  /** Primary key columns. */
  key: string[];
  /** Rows belong to an organization through this column. */
  org?: "organization_id" | "id";
  /** Rows belong to a deal (child tables without organization_id). */
  deal?: boolean;
  /** Columns that exist only in the app model or are generated by Postgres. */
  strip?: string[];
  /** Load order; the app keeps these newest-first. */
  newestFirst?: boolean;
};

/** Write order respects foreign keys; deletes run in reverse. */
const TABLES: [TableName, TableSpec][] = [
  ["organizations", { key: ["id"], org: "id" }],
  ["profiles", { key: ["id"], strip: ["password", "reset_token", "reset_expires"] }],
  ["teams", { key: ["id"], org: "organization_id" }],
  ["memberships", { key: ["id"], org: "organization_id" }],
  ["invitations", { key: ["id"], org: "organization_id", newestFirst: true }],
  ["pipelines", { key: ["id"], org: "organization_id" }],
  ["stages", { key: ["id"], org: "organization_id" }],
  ["companies", { key: ["id"], org: "organization_id" }],
  ["contacts", { key: ["id"], org: "organization_id" }],
  ["lost_reasons", { key: ["id"], org: "organization_id" }],
  ["tags", { key: ["id"], org: "organization_id" }],
  ["products", { key: ["id"], org: "organization_id" }],
  ["deals", { key: ["id"], org: "organization_id", strip: ["search"] }],
  ["deal_contacts", { key: ["id"], deal: true }],
  ["deal_tags", { key: ["deal_id", "tag_id"], deal: true }],
  ["activities", { key: ["id"], org: "organization_id" }],
  ["notes", { key: ["id"], org: "organization_id", newestFirst: true }],
  ["deal_products", { key: ["id"], deal: true, strip: ["subtotal"] }],
  ["stage_history", { key: ["id"], deal: true }],
  ["audit_logs", { key: ["id"], org: "organization_id", newestFirst: true }],
  ["notifications", { key: ["id"], org: "organization_id", newestFirst: true }],
  ["saved_views", { key: ["id"], org: "organization_id", newestFirst: true }],
];

const PAGE = 1000;

async function fetchAll(client: SupabaseClient, table: TableName, spec: TableSpec): Promise<Row[]> {
  const rows: Row[] = [];
  for (let from = 0; ; from += PAGE) {
    let query = client.from(table).select("*");
    if (table === "stage_history") query = query.order("changed_at", { ascending: true });
    else if (spec.key.length === 1 && table !== "deal_contacts" && table !== "deal_products") {
      query = query.order("created_at", { ascending: !spec.newestFirst });
    }
    for (const column of spec.key) query = query.order(column, { ascending: true });
    const { data, error } = await query.range(from, from + PAGE - 1);
    if (error) throw new Error(`load ${table}: ${error.message}`);
    rows.push(...(data as Row[]));
    if (!data || data.length < PAGE) return rows;
  }
}

/** Everything the signed-in user can read (RLS), shaped like the demo store. */
export async function loadSupabaseStore(client: SupabaseClient): Promise<Store> {
  const results = await Promise.all(TABLES.map(([table, spec]) => fetchAll(client, table, spec)));
  const store = { version: STORE_VERSION, seeded_on: "" } as Store;
  TABLES.forEach(([table], index) => {
    const rows = results[index] ?? [];
    if (table === "deals") rows.forEach((row) => delete row.search);
    if (table === "profiles") {
      rows.forEach((row) => {
        row.email = row.email ?? "";
        row.password = "";
        row.reset_token = null;
        row.reset_expires = null;
      });
    }
    (store as Record<TableName, Row[]>)[table] = rows;
  });
  return store;
}

function rowKey(row: Row, spec: TableSpec) {
  return spec.key.map((column) => String(row[column])).join("|");
}

function payload(row: Row, spec: TableSpec) {
  if (!spec.strip) return row;
  const copy = { ...row };
  spec.strip.forEach((column) => delete copy[column]);
  return copy;
}

export type CommitScope = {
  /** Organizations the actor may write to. New organizations created in this commit are added automatically. */
  organizations: string[];
  /** Profiles the actor may update (normally only their own). */
  profiles: string[];
};

class ScopeError extends Error {}

/**
 * Writes the difference between two store snapshots. Only rows that changed are sent, so
 * concurrent edits to different records don't overwrite each other.
 */
export async function commitSupabaseStore(before: Store, after: Store, scope: CommitScope) {
  const admin = createAdminClient();
  const allowedOrgs = new Set(scope.organizations);
  const beforeOrgs = new Set(before.organizations.map((org) => org.id));
  after.organizations.forEach((org) => {
    if (!beforeOrgs.has(org.id)) allowedOrgs.add(org.id);
  });
  const allowedDeals = new Set(
    [...before.deals, ...after.deals].filter((deal) => allowedOrgs.has(deal.organization_id)).map((deal) => deal.id),
  );
  const allowedProfiles = new Set(scope.profiles);

  function assertScope(table: TableName, spec: TableSpec, row: Row) {
    const ok = spec.org
      ? allowedOrgs.has(String(row[spec.org]))
      : spec.deal
        ? allowedDeals.has(String(row.deal_id))
        : table === "profiles"
          ? allowedProfiles.has(String(row.id))
          : false;
    if (!ok) throw new ScopeError(`write outside scope: ${table} ${rowKey(row, spec)}`);
  }

  const changes = TABLES.map(([table, spec]) => {
    const previous = new Map((before[table] as unknown as Row[]).map((row) => [rowKey(row, spec), row]));
    const next = new Map((after[table] as unknown as Row[]).map((row) => [rowKey(row, spec), row]));
    const upserts: Row[] = [];
    const deletes: Row[] = [];
    next.forEach((row, key) => {
      const old = previous.get(key);
      if (!old || JSON.stringify(old) !== JSON.stringify(row)) upserts.push(row);
    });
    previous.forEach((row, key) => {
      if (!next.has(key)) deletes.push(row);
    });
    upserts.forEach((row) => assertScope(table, spec, row));
    deletes.forEach((row) => assertScope(table, spec, row));
    return { table, spec, upserts, deletes };
  });

  for (const { table, spec, upserts } of changes) {
    if (upserts.length === 0) continue;
    const { error } = await admin
      .from(table)
      .upsert(upserts.map((row) => payload(row, spec)), { onConflict: spec.key.join(",") });
    if (error) throw new Error(`upsert ${table}: ${error.message}`);
  }

  for (const { table, spec, deletes } of [...changes].reverse()) {
    if (deletes.length === 0) continue;
    if (spec.key.length === 1) {
      const column = spec.key[0] ?? "id";
      const { error } = await admin.from(table).delete().in(column, deletes.map((row) => String(row[column])));
      if (error) throw new Error(`delete ${table}: ${error.message}`);
      continue;
    }
    for (const row of deletes) {
      let query = admin.from(table).delete();
      for (const column of spec.key) query = query.eq(column, String(row[column]));
      const { error } = await query;
      if (error) throw new Error(`delete ${table}: ${error.message}`);
    }
  }
}

export function emptyStore(): Store {
  const store = { version: STORE_VERSION, seeded_on: "" } as Store;
  TABLES.forEach(([table]) => {
    (store as Record<TableName, Row[]>)[table] = [];
  });
  return store;
}
